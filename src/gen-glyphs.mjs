// Rebuilds src/glyphs.js from the Rubik Mono One font files: `npm run glyphs`.
import opentype from 'opentype.js';
import fs from 'fs';

const dir = 'node_modules/@fontsource/rubik-mono-one/files/';
const load = f => { const b = fs.readFileSync(dir + f); return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); };
const latin = load('rubik-mono-one-latin-400-normal.woff'), cyrillic = load('rubik-mono-one-cyrillic-400-normal.woff');
const k = 2 / latin.charToGlyph('H').getBoundingBox().y2, r = v => Math.round(v * k * 1000) / 1000;
const out = {};
for (const [font, chars] of [[latin, 'PELYKH'], [cyrillic, 'ПЕЛИХ']]) for (const ch of chars) {
  const g = font.charToGlyph(ch), bb = g.getBoundingBox(), cx = (bb.x1 + bb.x2) / 2, c = [];
  for (const m of g.path.commands) {
    if (m.type === 'M' || m.type === 'L') c.push(m.type, r(m.x - cx), r(m.y));
    else if (m.type === 'Q') c.push('Q', r(m.x1 - cx), r(m.y1), r(m.x - cx), r(m.y));
    else if (m.type === 'C') c.push('C', r(m.x1 - cx), r(m.y1), r(m.x2 - cx), r(m.y2), r(m.x - cx), r(m.y));
  }
  out[ch] = { w: r(bb.x2 - bb.x1), c };
}
fs.writeFileSync('src/glyphs.js', '// Outlines of Rubik Mono One (SIL Open Font License), cap height = 2 units, centred on x.\n// Generated by src/gen-glyphs.mjs; do not edit by hand.\nexport const GLYPHS = ' + JSON.stringify(out) + ';\n');
