const store = {
  get(k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
  set(k, v) { try { localStorage.setItem(k, v); } catch (e) {} }
};
export const CAST_UK = { P: 'П', E: 'Е', L: 'Л', Y: 'И', K: 'K', H: 'Х' };
let lang = store.get('pelykh.lang') || ((navigator.language || '').toLowerCase().startsWith('uk') ? 'uk' : 'en');
if (!COPY[lang]) lang = 'en';
const listeners = [];
export const getLang = () => lang;
export const t = k => COPY[lang][k];
export const onLang = fn => listeners.push(fn);

export function applyCopy() {
  const c = COPY[lang];
  document.documentElement.lang = lang; document.title = c.docTitle;
  document.querySelectorAll('[data-t]').forEach(el => { el.textContent = c[el.dataset.t]; });
  document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  document.querySelectorAll('[data-cast]').forEach(row => {
    const id = row.dataset.cast, [voice, bio] = c.cast[id], letter = lang === 'uk' ? CAST_UK[id] : id;
    const btn = row.querySelector('button');
    btn.textContent = letter; btn.setAttribute('aria-label', `${c.hear} ${letter}`);
    row.querySelector('.voice').textContent = voice; row.querySelector('.bio').textContent = bio;
    row.classList.toggle('away', lang === 'uk' && id === 'K');
  });
  document.querySelectorAll('.stamp').forEach(s => { s.textContent = c.onLeave; });
  const ul = document.getElementById('rules'); ul.textContent = '';
  for (const r of c.rules) { const li = document.createElement('li'); li.textContent = r; ul.appendChild(li); }
  document.querySelectorAll('.marquee span').forEach(s => { s.textContent = c.marquee.repeat(4); });
  const cv = document.getElementById('stage'); if (cv) cv.setAttribute('aria-label', c.stageAlt);
}
export function setLang(l) {
  if (l === lang || !COPY[l]) return;
  lang = l; store.set('pelykh.lang', l); applyCopy(); listeners.forEach(fn => fn(l));
}
